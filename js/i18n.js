  const I18N = {
    lang: 'ar',
    t(key, vars) {
      const d = DICT[this.lang] || DICT.ar;
      let s = (key in d) ? d[key] : (DICT.ar[key] !== undefined ? DICT.ar[key] : key);
      if (vars) Object.keys(vars).forEach(k => { s = s.replace('{' + k + '}', vars[k]); });
      return s;
    },
    set(lang, save) {
      if (!DICT[lang]) lang = 'ar';
      this.lang = lang;
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
      if (save !== false) { try { localStorage.setItem('ma_lang', lang); } catch (e) {} }
    },
    init() {
      let l = 'ar';
      try { l = localStorage.getItem('ma_lang') || 'ar'; } catch (e) {}
      this.set(l, false);
      return l;
    },
    apply(root) {
      (root || document).querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = this.t(el.getAttribute('data-i18n'));
      });
      (root || document).querySelectorAll('[data-i18n-ph]').forEach(el => {
        el.setAttribute('placeholder', this.t(el.getAttribute('data-i18n-ph')));
      });
    }
  };

